export function parseMediaState(
  value: string | string[] | undefined,
): MediaState | undefined {
  const state = Array.isArray(value) ? value[0] : value;
  return state === "normal" ||
    state === "loading" ||
    state === "empty" ||
    state === "error" ||
    state === "permission-denied"
    ? state
    : undefined;
}
