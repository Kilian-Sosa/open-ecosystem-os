import type {
  OcrJobDetail,
  OcrLifecycleEntry,
  OcrLifecyclePhase,
} from "@/lib/media-api";

export type MediaState =
  | "normal"
  | "loading"
  | "empty"
  | "error"
  | "permission-denied";

function eventEntry(
  entryId: string,
  label: string,
  phase: OcrLifecyclePhase,
  eventType: string,
  occurredAt: string,
  source: string,
  correlationId: string,
  causationId: string | null,
  status: string,
  consumers: string[] = [],
): OcrLifecycleEntry {
  return {
    entryId,
    phase,
    kind: "event",
    label,
    status,
    observed: true,
    occurredAt,
    source,
    event: {
      eventId: entryId,
      eventType,
      eventVersion: 1,
      correlationId,
      causationId,
      publicationState: "publish_recorded",
      publishedAt: occurredAt,
      consumptions: consumers.map((consumer) => ({
        consumer,
        state: "consumption_recorded",
        consumedAt: occurredAt,
      })),
    },
    workflow: null,
    retry: null,
    failure: null,
    resource: null,
  };
}

function workflowEntry(
  entryId: string,
  label: string,
  occurredAt: string,
  status: string,
  stepKey: string | null,
  actionType: string | null,
): OcrLifecycleEntry {
  return {
    entryId,
    phase: "workflow",
    kind: stepKey ? "workflow_step" : "workflow_execution",
    label,
    status,
    observed: true,
    occurredAt,
    source: "flows",
    event: null,
    workflow: {
      executionId: "wfe_invoice_demo",
      workflowId: "flow_invoice_automation",
      workflowVersionId: "wfv_invoice_automation_v2",
      workflowVersionNumber: 2,
      stepKey,
      actionType,
      retryCount: 0,
    },
    retry: null,
    failure: null,
    resource: {
      resourceType: stepKey ? "workflow_step" : "workflow_execution",
      resourceId: entryId,
    },
  };
}

function pendingEntry(
  entryId: string,
  label: string,
  phase: "ocr" | "workflow",
  attemptCount: number,
  maxAttempts: number,
  nextAttemptAt: string | null,
): OcrLifecycleEntry {
  return {
    entryId,
    phase,
    kind: "pending",
    label,
    status: "awaiting",
    observed: false,
    occurredAt: null,
    source: phase === "ocr" ? "media" : "flows",
    event: null,
    workflow: null,
    retry: { attemptCount, maxAttempts, nextAttemptAt },
    failure: null,
    resource: null,
  };
}

